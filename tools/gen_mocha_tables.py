#!/usr/bin/env python3
"""Generates src/mocha_tables.h: the colour remap tables used by src/mocha.c.

KhiCAS's own screens (graphs, catalogue, file menu, script editor) draw with a
fixed palette. mocha.c recolours each frame before it reaches the LCD; this
script decides what each KhiCAS colour becomes in Catppuccin Mocha.
Tables are small open-addressed hashes keyed by the RGB565 source colour.
"""
import os

def c565(hexrgb):
    r, g, b = (int(hexrgb[i:i + 2], 16) for i in (0, 2, 4))
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)

def blend(a, b, t):
    pa = [int(a[i:i + 2], 16) for i in (0, 2, 4)]
    pb = [int(b[i:i + 2], 16) for i in (0, 2, 4)]
    return '%02x%02x%02x' % tuple(round(x + (y - x) * t) for x, y in zip(pa, pb))

M = dict(base='1e1e2e', mantle='181825', crust='11111b', surface0='313244', surface1='45475a',
         surface2='585b70', overlay0='6c7086', text='cdd6f4', subtext0='a6adc8', mauve='cba6f7',
         red='f38ba8', green='a6e3a1', blue='89b4fa', yellow='f9e2af', peach='fab387', pink='f5c2e7',
         teal='94e2d5', sky='89dceb', lavender='b4befe', maroon='eba0ac')

def tint(accent, t=0.22):   # dark background tinted with an accent (menu bars)
    return blend(M['base'], M[accent], t)

# Rows 24-197: KhiCAS colour -> Mocha colour
body = {
    0xFFFF: M['base'], 0x0000: M['text'],
    0xF800: M['red'], 0x07E0: M['green'], 0x001F: M['mauve'], 0xF81F: M['pink'],
    0xFFE0: tint('yellow', 0.30), 0x07FF: tint('teal'), 0xFD20: M['peach'], 0xFDE0: M['yellow'],
    0xC118: M['peach'], 0xCA00: M['sky'], 0xA145: M['sky'], 0x8010: M['mauve'], 0x8410: M['overlay0'],
    0xFE1F: M['surface0'], 0xFC1F: M['surface0'], 0xFFF0: tint('yellow'), 0xFFE8: tint('yellow'),
    0xF648: tint('red'), 0x861F: tint('teal'), 0x87F0: tint('green'),
    0x0011: M['blue'], 0x8800: M['maroon'], 0x0320: M['green'], 0x8811: M['pink'], 0x0451: M['teal'],
}
# Rows 0-23: the OS status bar becomes a mauve title bar, as in Upsilon
top = {0xFFFF: M['mauve'], 0x0000: M['crust']}
# Rows 198-215: F-key menu bar, where orange is a background
bottom = dict(body)
bottom[0xFD20] = tint('peach')

def resolve(table):
    return {k: c565(v) for k, v in table.items()}

body, top, bottom = resolve(body), resolve(top), resolve(bottom)

# A target colour must never be a source, so recolouring twice changes nothing
targets = set(body.values()) | set(top.values()) | set(bottom.values())
for t in (body, top, bottom):
    assert not (targets & set(t)), 'a Mocha colour is also a source colour'

SIZE, K = 64, 0x9E37

def hashed(table):
    slots = [None] * SIZE
    for k, v in table.items():
        h = ((k * K) >> 10) & (SIZE - 1)
        while slots[h] is not None:
            h = (h + 1) & (SIZE - 1)
        slots[h] = (k, v)
    return ','.join('0xFFFFFFFFu' if s is None else '0x%04X%04Xu' % s for s in slots)

out = ['/* Generated by tools/gen_mocha_tables.py: Catppuccin Mocha remap tables */',
       '#define MOCHA_HASH_K 0x%X' % K, '#define MOCHA_HASH_SIZE %d' % SIZE]
for name, table in (('body', body), ('top', top), ('bottom', bottom)):
    out.append('static const unsigned int mocha_%s[MOCHA_HASH_SIZE]={%s};' % (name, hashed(table)))
for n in ('base', 'text', 'surface1', 'surface0', 'crust', 'mauve'):
    out.append('#define MOCHA_%s 0x%04X' % (n.upper(), c565(M[n])))

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'mocha_tables.h')
open(path, 'w').write('\n'.join(out) + '\n')
print('wrote', os.path.normpath(path))
